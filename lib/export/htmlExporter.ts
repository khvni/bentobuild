/**
 * Extract custom styles from page sections and components
 */
function extractCustomStyles(page: Page): string {
  // This can be expanded to generate custom CSS classes
  // based on unique style combinations in the page
  return '/* Custom component styles */';
}

/**
 * Generate Google Fonts link tag
 */
function generateGoogleFontsLink(page: Page): string {
  const fonts = new Set<string>();

  // Collect all unique fonts from the page
  page.sections.forEach(section => {
    if (section.style.fontFamily) {
      fonts.add(section.style.fontFamily);
    }

    section.children.forEach(component => {
      if (component.style.fontFamily) {
        fonts.add(component.style.fontFamily);
      }
    });
  });

  if (fonts.size === 0) return '';

  const families = Array.from(fonts).map(f =>
    `family=${f.replace(/ /g, '+')}:wght@400;600;700`
  ).join('&');

  return `<link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?${families}&display=swap" rel="stylesheet">`;
}

/**
 * Get position-specific inline styles
 */
function getPositionStyle(position: any, parentLayout: any): string {
  const styles: string[] = [];

  if (position.type === 'absolute' && position.absolute) {
    styles.push('position: absolute');
    styles.push(`left: ${position.absolute.x}px`);
    styles.push(`top: ${position.absolute.y}px`);
  }

  if (parentLayout.type === 'grid' && position.grid) {
    if (position.grid.column) {
      styles.push(`grid-column: ${position.grid.column}`);
    }
    if (position.grid.row) {
      styles.push(`grid-row: ${position.grid.row}`);
    }
  }

  return styles.join('; ');
}

/**
 * Get component-specific inline styles
 */
function getComponentStyles(style: any): string {
  const styles: string[] = [];

  if (style.backgroundColor) styles.push(`background-color: ${style.backgroundColor}`);
  if (style.textColor) styles.push(`color: ${style.textColor}`);
  if (style.fontFamily) styles.push(`font-family: '${style.fontFamily}', sans-serif`);
  if (style.fontSize) styles.push(`font-size: ${style.fontSize}`);
  if (style.fontWeight) styles.push(`font-weight: ${style.fontWeight}`);
  if (style.padding) styles.push(`padding: ${style.padding}`);
  if (style.margin) styles.push(`margin: ${style.margin}`);
  if (style.borderRadius) styles.push(`border-radius: ${style.borderRadius}`);

  return styles.join('; ');
}

/**
 * Get section-specific inline styles
 */
function getInlineStyles(style: any): string {
  const styles: string[] = [];

  if (style.backgroundColor) styles.push(`background-color: ${style.backgroundColor}`);
  if (style.textColor) styles.push(`color: ${style.textColor}`);
  if (style.padding) styles.push(`padding: ${style.padding}`);
  if (style.fontFamily) styles.push(`font-family: '${style.fontFamily}', sans-serif`);

  return styles.join('; ');
}

/**
 * Escape HTML special characters to prevent XSS
 */
function escapeHTML(str: string): string {
  if (!str) return '';

  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}
