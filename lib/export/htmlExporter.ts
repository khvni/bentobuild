/**
 * HTML Export Engine for Bentoblocks
 *
 * Converts Page/Section/Component architecture to standalone HTML
 * with embedded CSS and Google Fonts integration.
 *
 * @module lib/export/htmlExporter
 */

import { Page, Section, Component } from '@/types/canvas.types';

/**
 * Export a complete Page to standalone HTML
 *
 * @param page - Page object with sections and components
 * @returns Complete HTML document as string
 */
export function exportToHTML(page: Page): string {
  const sections = page.sections.sort((a, b) => a.order - b.order);

  const sectionsHTML = sections.map(section => renderSection(section)).join('\n\n');

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${escapeHTML(page.metadata?.title || 'Bentoblocks Site')}</title>
  ${page.metadata?.description ? `<meta name="description" content="${escapeHTML(page.metadata.description)}">` : ''}
  ${page.metadata?.favicon ? `<link rel="icon" href="${escapeHTML(page.metadata.favicon)}">` : ''}
  ${generateGoogleFontsLink(page)}
  <style>${generateCSS(page)}</style>
</head>
<body>
  ${sectionsHTML}
</body>
</html>`;
}

/**
 * Render a Section to HTML
 */
function renderSection(section: Section): string {
  const layoutClass = getLayoutClass(section.layout);
  const componentsHTML = section.children
    .map(c => renderComponent(c, section.layout))
    .join('\n    ');

  const sectionStyles = getInlineStyles(section.style);

  return `  <section
    id="section-${section.id}"
    class="${layoutClass} section-${section.variant}"
    ${sectionStyles ? `style="${sectionStyles}"` : ''}
  >
    ${componentsHTML}
  </section>`;
}

/**
 * Render a Component to HTML
 */
function renderComponent(component: Component, parentLayout: any): string {
  const positionStyle = getPositionStyle(component.position, parentLayout);
  const componentStyles = getComponentStyles(component.style);
  const styleAttr = [positionStyle, componentStyles].filter(Boolean).join('; ');

  switch (component.type) {
    case 'heading': {
      const level = component.content.level;
      return `<h${level} ${styleAttr ? `style="${styleAttr}"` : ''}>${escapeHTML(component.content.text)}</h${level}>`;
    }

    case 'text':
      return `<div class="text-content" ${styleAttr ? `style="${styleAttr}"` : ''}>${component.content.body}</div>`;

    case 'button': {
      const variantClass = `btn-${component.content.variant}`;
      return `<a href="${escapeHTML(component.content.url)}" class="btn ${variantClass}" ${styleAttr ? `style="${styleAttr}"` : ''}>
        ${escapeHTML(component.content.text)}
      </a>`;
    }

    case 'image':
      return `<figure ${styleAttr ? `style="${styleAttr}"` : ''}>
        <img src="${escapeHTML(component.content.src)}" alt="${escapeHTML(component.content.alt)}" ${component.content.objectFit ? `style="object-fit: ${component.content.objectFit}"` : ''} />
        ${component.content.caption ? `<figcaption>${escapeHTML(component.content.caption)}</figcaption>` : ''}
      </figure>`;

    case 'link':
      return `<a href="${escapeHTML(component.content.url)}" class="link-component" ${styleAttr ? `style="${styleAttr}"` : ''}>
        <span class="link-text">${escapeHTML(component.content.text)}</span>
        ${component.content.description ? `<span class="link-desc">${escapeHTML(component.content.description)}</span>` : ''}
      </a>`;

    case 'spacer':
      return `<div class="spacer" style="height: ${component.content.height}px;"></div>`;

    case 'divider':
      return `<hr style="border: none; height: ${component.content.thickness || 2}px; background: ${component.content.color || '#e5e7eb'}; margin: 1rem 0;" />`;

    default:
      return '';
  }
}

/**
 * Get layout CSS class based on layout configuration
 */
function getLayoutClass(layout: any): string {
  if (layout.type === 'stack') {
    return `layout-stack layout-stack-${layout.direction || 'vertical'}`;
  } else if (layout.type === 'grid') {
    return `layout-grid layout-grid-${layout.columns || 2}`;
  } else if (layout.type === 'absolute') {
    return `layout-absolute`;
  }
  return '';
}

